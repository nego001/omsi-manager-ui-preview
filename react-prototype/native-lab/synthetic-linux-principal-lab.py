#!/usr/bin/env python3
"""Disposable GitHub-hosted Linux OS-principal test; NOT a product service.

Runs only with an explicit hosted-runner gate and sudo. Creates temporary local
users and a socket/secret under RUNNER_TEMP; removes them before returning.
There is no game path, mod installation, persistent daemon, or client signing.
"""
import argparse
import json
import os
import pathlib
import select
import shutil
import signal
import socket
import stat
import struct
import subprocess
import sys
import tempfile
import time
import uuid

PREFIX = "omsi-principal-lab-"
SECRET_NAME = "synthetic-only-key"
SO_PEERCRED = getattr(socket, "SO_PEERCRED", None)


def require(condition, reason):
    if not condition:
        raise RuntimeError("Linux principal lab refused: " + reason)


def run_as(username, script, mode, *args):
    cmd = ["runuser", "-u", username, "--", sys.executable,
           str(script), mode, *map(str, args)]
    return subprocess.run(cmd, text=True, capture_output=True,
                          timeout=10, check=False)


def client(socket_path, payload):
    with socket.socket(socket.AF_UNIX, socket.SOCK_STREAM) as sock:
        sock.settimeout(4)
        sock.connect(socket_path)
        sock.sendall(payload.encode("utf-8") + b"\n")
        return sock.recv(32).decode("ascii").strip()


def server(socket_path, accepted_uid, secret_path):
    require(SO_PEERCRED is not None, "SO_PEERCRED unavailable")
    secret_path = pathlib.Path(secret_path)
    # The only key in this test is generated by the service UID, and is never
    # sent over the socket. This is a disposable permissions canary, not a
    # production signing key or an authorization for any data operations.
    descriptor = os.open(secret_path, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    try:
        os.write(descriptor, os.urandom(32))
        os.fsync(descriptor)
    finally:
        os.close(descriptor)
    with socket.socket(socket.AF_UNIX, socket.SOCK_STREAM) as listening:
        listening.bind(socket_path)
        # Deliberately world-connectable to prove rejection by SO_PEERCRED,
        # even when Unix socket file permissions alone allow connection.
        os.chmod(socket_path, 0o666)
        listening.listen(5)
        listening.settimeout(15)
        print("READY", flush=True)
        while True:
            try:
                connection, _ = listening.accept()
            except socket.timeout:
                return
            with connection:
                connection.settimeout(3)
                try:
                    raw = connection.recv(161)
                    creds = connection.getsockopt(socket.SOL_SOCKET, SO_PEERCRED, 12)
                    pid, peer_uid, peer_gid = struct.unpack("3i", creds)
                    valid = (pid > 0 and peer_uid == int(accepted_uid)
                             and len(raw) <= 160 and raw.endswith(b"\n"))
                    if valid:
                        line = raw[:-1].decode("utf-8", errors="strict")
                        obj = json.loads(line)
                        valid = (type(obj) is dict
                                 and set(obj) == {"id", "op"}
                                 and type(obj.get("id")) is int
                                 and obj["id"] >= 1
                                 and obj["op"] == "probe"
                                 and json.dumps(obj, separators=(",", ":")) == line)
                    connection.sendall(b"ALLOWED\n" if valid else b"DENIED\n")
                except (ValueError, UnicodeError, OSError, KeyError, TypeError):
                    try:
                        connection.sendall(b"DENIED\n")
                    except OSError:
                        pass


def access_probe(target):
    try:
        with open(target, "rb") as handle:
            payload = handle.read(33)
        print("HAS_ACCESS" if len(payload) == 32 else "INVALID", flush=True)
    except PermissionError:
        print("NO_ACCESS", flush=True)
    except OSError:
        print("INVALID", flush=True)


def orchestrate(script):
    require(sys.platform.startswith("linux"), "Linux required")
    require(os.geteuid() == 0, "requires sudo on disposable runner")
    require(os.environ.get("GITHUB_ACTIONS") == "true",
            "only allowed inside GitHub Actions")
    require(os.environ.get("OMSI_SYNTHETIC_HOSTED_RUNNER") == "github-hosted",
            "must be an explicitly declared GitHub-hosted runner")
    root_env = os.environ.get("RUNNER_TEMP", "")
    require(bool(root_env) and pathlib.Path(root_env).is_dir(),
            "RUNNER_TEMP missing")
    require(SO_PEERCRED is not None, "Linux peer credentials unavailable")
    # Never work outside a newly allocated GitHub runner TEMP child.
    root = pathlib.Path(tempfile.mkdtemp(prefix=PREFIX, dir=root_env))
    os.chmod(root, 0o755)
    # GitHub checkout is intentionally not traversable by synthetic UIDs.
    # Copy only this fixture worker into the disposable directory instead
    # of weakening checkout permissions or accessing repo files as a service.
    worker = root / "synthetic-linux-principal-lab.py"
    shutil.copyfile(script, worker)
    os.chmod(worker, 0o644)
    added = []
    proc = None
    token = uuid.uuid4().hex[:7]
    service, trusted, outsider = [f"omsi_{role}_{token}"
                                 for role in ("s", "c", "u")]
    try:
        for username in (service, trusted, outsider):
            subprocess.run(["useradd", "--system", "--no-create-home",
                            "--shell", "/usr/sbin/nologin", username],
                           check=True, timeout=10)
            added.append(username)

        def uid(username):
            out = subprocess.run(["id", "-u", username], capture_output=True,
                                 text=True, check=True, timeout=5)
            return int(out.stdout.strip())

        require(len({uid(service), uid(trusted), uid(outsider)}) == 3,
                "different kernel user identities required")
        private = root / "service-private"
        ipc = root / "ipc"
        private.mkdir(mode=0o700)
        ipc.mkdir(mode=0o755)
        os.chown(private, uid(service), -1)
        os.chmod(private, 0o700)
        # Only the service UID can create/remove the disposable socket;
        # clients may traverse this test directory and attempt connection.
        os.chown(ipc, uid(service), -1)
        os.chmod(ipc, 0o755)
        sock_path = ipc / "synthetic.sock"
        key_path = private / SECRET_NAME
        cmd = ["runuser", "-u", service, "--", sys.executable,
               str(worker), "server", str(sock_path), str(uid(trusted)),
               str(key_path)]
        proc = subprocess.Popen(cmd, stdout=subprocess.PIPE,
                                stderr=subprocess.PIPE, text=True,
                                start_new_session=True)
        readable, _, _ = select.select([proc.stdout], [], [], 10)
        ready = bool(readable) and proc.stdout.readline().strip() == "READY"
        if not ready:
            # Diagnostics are emitted only for a child that already exited.
            # No secret bytes or synthetic keys are logged.
            if proc.poll() is not None:
                detail = (proc.stderr.read(1500) or "").strip()
                print("LAB_SERVER_FAILURE: " + detail, file=sys.stderr)
            require(False, "fixture-only server failed to become ready")
        require(key_path.stat().st_uid == uid(service),
                "service-only synthetic secret must have service UID")
        require(stat.S_IMODE(key_path.stat().st_mode) == 0o600,
                "service-only synthetic secret must be mode 0600")
        print("PASS_SEPARATE_LINUX_UIDS", flush=True)

        for user, expected in [(service, "HAS_ACCESS"),
                               (trusted, "NO_ACCESS"),
                               (outsider, "NO_ACCESS")]:
            result = run_as(user, worker, "access", key_path)
            require(result.returncode == 0 and result.stdout.strip() == expected,
                    "synthetic key access permissions incorrect")
        print("PASS_SERVICE_ONLY_FILE_ACCESS", flush=True)

        # The socket is intentionally connectable by all users. Only the
        # kernel-reported UID, not a caller-supplied JSON field, authorizes.
        cases = [
            (trusted, '{"id":1,"op":"probe"}', "ALLOWED"),
            (outsider, '{"id":2,"op":"probe"}', "DENIED"),
            (outsider, '{"id":3,"op":"probe","uid":%s}' % uid(trusted), "DENIED"),
            (trusted, '{"id":4,"op":"install"}', "DENIED"),
            (trusted, '{"id":5,"op":"probe","path":"/tmp"}', "DENIED"),
        ]
        for username, payload, expected in cases:
            res = run_as(username, worker, "client", sock_path, payload)
            require(res.returncode == 0 and res.stdout.strip() == expected,
                    "socket OS-peer-credential or command denial failed")
        print("PASS_SO_PEERCRED_AND_DENIED_COMMANDS", flush=True)

        # The synthetic server cannot modify mod directories: this protocol
        # returns only ALLOWED/DENIED to a fixed one-word probe.
        require(proc.poll() is None, "server exited unexpectedly")
        print("PASS_DISPOSABLE_NO_SERVICE_INSTALL", flush=True)
    finally:
        if proc is not None and proc.poll() is None:
            try:
                os.killpg(proc.pid, signal.SIGTERM)
            except ProcessLookupError:
                pass
            try:
                proc.wait(timeout=4)
            except subprocess.TimeoutExpired:
                os.killpg(proc.pid, signal.SIGKILL)
                proc.wait(timeout=4)
        shutil.rmtree(root, ignore_errors=True)
        for username in reversed(added):
            subprocess.run(["userdel", username], check=True, timeout=10)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("mode", choices=("orchestrate", "server", "client", "access"))
    parser.add_argument("args", nargs="*")
    parsed = parser.parse_args()
    # Child modes also refuse direct invocation outside the same disposable
    # hosted runner: no general-purpose root path or socket-writing CLI.
    if parsed.mode != "orchestrate":
        require(sys.platform.startswith("linux")
                and os.environ.get("GITHUB_ACTIONS") == "true"
                and os.environ.get("OMSI_SYNTHETIC_HOSTED_RUNNER") == "github-hosted",
                "child restricted to disposable GitHub-hosted runner")
        temp = pathlib.Path(os.environ.get("RUNNER_TEMP", "/nonexistent")).resolve()
        if parsed.mode == "server":
            require(len(parsed.args) == 3, "wrong server arguments")
            endpoint = pathlib.Path(parsed.args[0]).resolve()
            canary = pathlib.Path(parsed.args[2]).resolve()
            fixture = endpoint.parent.parent
            require(fixture.parent == temp and fixture.name.startswith(PREFIX)
                    and endpoint == fixture / "ipc" / "synthetic.sock"
                    and canary == fixture / "service-private" / SECRET_NAME,
                    "server cannot access arbitrary paths")
        else:
            require(len(parsed.args) >= 1, "missing fixture path")
            target = pathlib.Path(parsed.args[0]).resolve()
            fixture = target.parent.parent
            require(fixture.parent == temp and fixture.name.startswith(PREFIX),
                    "child cannot access arbitrary paths")
    if parsed.mode == "orchestrate":
        require(not parsed.args, "unexpected orchestrator arguments")
        orchestrate(pathlib.Path(__file__).resolve())
    elif parsed.mode == "server":
        require(len(parsed.args) == 3, "wrong server arguments")
        server(parsed.args[0], parsed.args[1], parsed.args[2])
    elif parsed.mode == "client":
        require(len(parsed.args) == 2, "wrong client arguments")
        print(client(*parsed.args), flush=True)
    else:
        require(len(parsed.args) == 1, "wrong access-probe arguments")
        access_probe(parsed.args[0])


if __name__ == "__main__":
    main()
