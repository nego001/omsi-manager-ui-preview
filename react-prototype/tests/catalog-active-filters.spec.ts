import {test,expect} from '@playwright/test';
import {resolve} from 'node:path';

test('chips do Catálogo removem cada critério com foco contínuo em 390 px',async({page})=>{
 await page.setViewportSize({width:390,height:820});
 await page.goto('/');
 const nav=page.getByRole('navigation',{name:'Navegação principal'});
 await nav.getByRole('button',{name:'Catálogo de mods'}).click();
 await expect(page.getByRole('group',{name:'Filtros ativos do catálogo'})).toHaveCount(0);
 await page.getByRole('button',{name:'OMSI 2',exact:true}).click();
 const category=page.getByRole('combobox',{name:'Filtrar categoria'});
 await category.selectOption('Mapas');
 const search=page.getByRole('textbox',{name:'Buscar mods'});
 await search.fill('serra');
 const chips=page.getByRole('group',{name:'Filtros ativos do catálogo'});
 await expect(chips.getByRole('button')).toHaveCount(3);
 await expect(page.getByText('1 resultado',{exact:true})).toBeVisible();
 const gameChip=chips.getByRole('button',{name:'Remover filtro de jogo do catálogo'});
 const categoryChip=chips.getByRole('button',{name:'Remover filtro de categoria do catálogo'});
 const searchChip=chips.getByRole('button',{name:'Remover filtro de pesquisa do catálogo'});
 await categoryChip.focus();
 await page.keyboard.press('Enter');
 await expect(searchChip).toBeFocused();
 await expect(category).toHaveValue('Todos');
 await expect(chips.getByRole('button')).toHaveCount(2);
 await searchChip.focus();
 await page.keyboard.press('Enter');
 await expect(gameChip).toBeFocused();
 await expect(search).toHaveValue('');
 await expect(page.getByText('3 resultados',{exact:true})).toBeVisible();
 await page.keyboard.press('Enter');
 await expect(chips).toHaveCount(0);
 await expect(page.getByText('7 resultados',{exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'Ônibus Urbano Clássico',exact:true})).toBeFocused();
 const overflow=await page.evaluate(()=>Math.max(0,document.documentElement.scrollWidth-document.documentElement.clientWidth));
 expect(overflow).toBeLessThanOrEqual(3);
});

test('chips do Catálogo respeitam JSON importado, favoritos e resultado vazio',async({page})=>{
 await page.goto('/');
 const nav=page.getByRole('navigation',{name:'Navegação principal'});
 await nav.getByRole('button',{name:'Catálogo de mods'}).click();
 await page.getByLabel('Arquivo JSON do catálogo').setInputFiles(resolve('examples/catalog.example.json'));
 const title='Ônibus urbano OF-1721';
 const favoriteCard=page.locator('.mod-card').filter({has:page.getByRole('button',{name:title,exact:true})});
 await favoriteCard.getByRole('button',{name:'Favoritar'}).click();
 await page.getByRole('button',{name:'Euro Truck Simulator 2',exact:true}).click();
 const category=page.getByRole('combobox',{name:'Filtrar categoria'});
 await category.selectOption('Ônibus');
 await expect(page.locator('.catalog-empty-filter')).toBeVisible();
 const chips=page.getByRole('group',{name:'Filtros ativos do catálogo'});
 await expect(chips.getByRole('button')).toHaveCount(2);
 const gameChip=chips.getByRole('button',{name:'Remover filtro de jogo do catálogo'});
 const categoryChip=chips.getByRole('button',{name:'Remover filtro de categoria do catálogo'});
 await gameChip.focus();
 await page.keyboard.press('Space');
 await expect(categoryChip).toBeFocused();
 await expect(page.getByText('1 resultado',{exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:title,exact:true})).toBeVisible();
 await categoryChip.click();
 await expect(chips).toHaveCount(0);
 await expect(page.getByRole('button',{name:title,exact:true})).toBeFocused();
 await expect(page.getByText('3 resultados',{exact:true})).toBeVisible();
 await expect(page.getByText('Origem: Importado: catalog.example.json')).toBeVisible();
 await expect(favoriteCard.getByRole('button',{name:'Retirar dos favoritos'})).toBeVisible();
 await page.getByRole('button',{name:title,exact:true}).click();
 await expect(page.getByRole('button',{name:'Instalar (bloqueado)'})).toBeDisabled();
 await expect(page.getByRole('button',{name:'Remover (bloqueado)'})).toBeDisabled();
});
